const BOOKS =
  'Genesis|Exodus|Ruth|Jonah|Micah|Isaiah|Psalms?|Proverbs|Matthew|Mark|Luke|John|Acts|Romans|1 Corinthians|Galatians|Ephesians|Philippians|Hebrews|James';
const REF = new RegExp(`\\b(?:${BOOKS})\\s\\d+(?::\\d+(?:[–-]\\d+)?)?(?:[–-]\\d+)?`);

function parse(category: QuestCategory, letter: string, raw: string, i: number): Quest {
  const m = raw.match(/^\((A|S)\)\s*/);
  const text = m ? raw.slice(m[0].length) : raw;
  const ref = text.match(REF)?.[0];
  return { id: `${letter}:${i + 1}`, category, tier: (m?.[1] as QuestTier | undefined) ?? 'n', text, ref };
}

export const QUESTS: Quest[] = SOURCES.flatMap(({ category, letter, list }) => list.map((raw, i) => parse(category, letter, raw, i)));

const BY_ID = new Map(QUESTS.map(q => [q.id, q]));
export const questById = (id: string) => BY_ID.get(id);

export const questsIn = (category: QuestCategory, tier: 'n' | 'bonus') =>
  QUESTS.filter(q => q.category === category && (tier === 'n' ? q.tier === 'n' : q.tier !== 'n'));
